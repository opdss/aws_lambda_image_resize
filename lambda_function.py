"""CloudFront Lambda@Edge 图片动态处理函数

在源站响应阶段拦截，根据 query string 中的 size / get_frame 参数
对 S3 原图做缩放 / GIF 抽帧，并通过 base64 直接返回或重定向。

参考:
    https://aws.amazon.com/cn/blogs/china/use-cloudfront-lambdaedge-for-transaction-processing/

注意:
    - bucket 名和目录名需全部小写以符合 S3 命名规范。
    - Lambda@Edge 响应 body 大小上限为 1024 * 1024，超过将写回 S3 并重定向。
"""
from __future__ import annotations

import base64
import os
import re
from io import BytesIO
from typing import Optional, Tuple
from urllib.parse import parse_qs

import boto3
from PIL import Image, ImageFile

# 动态图格式，需特殊处理以保持动画 / 抽帧
ANIMATED_FORMATS = ("gif", "webp")

# Lambda@Edge 响应 body 上限（字节）

# https://docs.aws.amazon.com/AmazonCloudFront/latest/DeveloperGuide/lambda-at-edge-function-restrictions.html
MAX_RESPONSE_BODY = 1024 * 1024

# 复用 S3 资源实例（Lambda 容器复用时不会重建）
s3 = boto3.resource("s3")

_INT_RE = re.compile(r"^\d+$")

# debug 模式
debug = False

def debugLog(*args, **kwargs):
    if debug:
        print("args:", args)
        print("kwargs:", kwargs)


def to_number(value: str) -> int:
    """把 query string 里的数字安全转成 int，非法值返回 0。"""
    if value is None:
        return 0
    value = value.strip()
    return int(value) if _INT_RE.match(value) else 0

def parse_query_string(query_str: str) -> dict:
    """解析 CloudFront 传入的 query string。
    s:
        - 优先级比下面两个参数w,h高，格式为 宽x高：x为小写字母，宽和高都必须大于0，否则视为无效
        - 参数有效的话，严格将图片按指定宽高缩放， 可能会使图片失真或比例失调，慎用
    w:·
        - 限宽值，不传或小于等于0无效
        - 限宽值有效的话，按这个宽等比例缩放，不拉伸
        - w,h都有效的话，将按限宽等比例缩放
    h:
        - 限高值，不传或小于等于0无效
        - 限高值有效的话，按这个高等比例缩放，不拉伸
        - w,h都有效的话，将按限宽等比例缩放
    f:
        - 限帧值，不传或小于等于0无效
        - 指定动图播放帧数量
    """
    parsed = parse_qs(query_str)
    # parse_qs 返回 {key: [values]}，只取首个
    params = {k: v[0] for k, v in parsed.items()}
    debugLog("query params", params=params)
    size = (to_number(params.get("w", "0")), to_number(params.get("h", "0")))
    # 严格指定尺寸
    strictSize = params.get("s", "")
    strict_mode = False
    if strictSize != "":
        parts = strictSize.split("x")
        if len(parts) == 2:
            w, h = to_number(parts[0]), to_number(parts[1])
            if w > 0 and h > 0:
                strict_mode = True
                size = (w, h)
    return {
        "strict_mode" : strict_mode,
        "size": size,
        "get_frame": to_number(params.get("f", "0")),
    }

def build_thumbnail_key(params: dict, uri: str) -> str:
    """根据处理参数构造缩略图回写到 S3 时使用的 key。"""
    size = params.get("size")
    prefix = f"{size[0]}x{size[1]}" if size else "0"
    get_frame = params.get("get_frame", 0)
    if get_frame and get_frame > 0:
        prefix = f"{prefix}_{get_frame}"
    return f"thumb/{prefix}{uri}"

def extract_bucket_name(s3_domain: str) -> str:
    """从 CloudFront 传入的 S3 origin domain 提取 bucket 名。"""
    return s3_domain.split(".")[0]

def should_skip_processing(object_key: str, params: dict) -> bool:
    """根据文件类型与参数判断是否跳过图片处理。"""
    ext = os.path.splitext(object_key)[1][1:].lower()
    is_animated = ext in ANIMATED_FORMATS
    size = params["size"]
    get_frame = params["get_frame"]

    if is_animated:
        # 动图：既不缩放也不抽帧时跳过
        return size == (0, 0) and get_frame <= 0

    # 静态图：没指定尺寸就跳过
    return size == (0, 0)

def resize_s3_image(
    bucket_name: str,
    object_key: str,
    params: dict,
) -> Tuple[Optional[BytesIO], str]:
    """从 S3 下载原图并处理；若缩图尺寸大于等于原图则返回 (None, '')。"""
    obj = s3.Object(bucket_name=bucket_name, key=object_key)
    img = Image.open(BytesIO(obj.get()["Body"].read()))

    # 目标尺寸不比原图小 → 不需要处理
    if params["size"] != (0, 0) and (params["strict_mode"] is False and params["size"][0] >= img.size[0] and params["size"][1] >= img.size[1]):
        return None, ""

    buffer = resize_image(img, params)
    fmt = (img.format or "").lower()
    return buffer, fmt

def upload_to_s3(bucket_name: str, object_key: str, img_buffer: BytesIO, ext: str) -> None:
    """把过大的处理结果回写到 S3，便于后续重定向访问。"""
    s3.Object(bucket_name=bucket_name, key=object_key).put(
        Body=img_buffer.getvalue(),
        ContentType=f"image/{ext.lower()}",
    )

def build_response(response: dict, img_buffer: BytesIO, ext: str) -> dict:
    """构造 200 响应，body 以 base64 形式供 CloudFront 解码后下发。"""
    response["status"] = "200"
    response["statusDescription"] = "Generated by CloudFront Original Response Function"
    response["body"] = base64.b64encode(img_buffer.getvalue()).decode()
    response["bodyEncoding"] = "base64"
    response["headers"]["content-type"] = [
        {"key": "Content-Type", "value": f"image/{ext.lower()}"}
    ]
    response["headers"]["content-encoding"] = [
        {"key": "Content-Encoding", "value": "base64"}
    ]
    debugLog(response=response)
    return response

def redirect_response(response: dict, object_key: str) -> dict:
    """构造 301 重定向响应，指向回写到 S3 的处理后图片。"""
    response["status"] = "301"
    response["statusDescription"] = "Moved Permanently"
    response["headers"]["location"] = [
        {"key": "Location", "value": f"/{object_key}"}
    ]
    debugLog(redirect=response)
    return response

def _calc_target_size(raw_size: Tuple[int, int], params_size: Optional[Tuple[int, int]], strict_mode: False) -> Tuple[int, int]:
    """根据原始尺寸与请求尺寸算出最终缩放尺寸，支持等比例。"""
    if params_size is None or params_size == (0, 0):
        return raw_size
    
    width, height = params_size
    #严格模式，且尺寸有效，直接返回该尺寸
    if strict_mode and width > 0 and height > 0:
        return width, height
    
    #取宽或者高作为缩放比例，宽优先
    raw_w, raw_h = raw_size
    if width > 0 and height > 0:
        if width < raw_w:
            height = 0
        else:
            width = 0
    #下面计算比例
    if width == 0:
        return int(raw_w * (height / raw_h)), height
    if height == 0:
        return width, int(raw_h * (width / raw_w))
    return width, height

def _resize_animated(img: ImageFile, target_size: Tuple[int, int], get_frame: int) -> BytesIO:
    """处理 GIF / WebP 动图，保留循环与 duration，必要时抽帧。"""
    n_frames = getattr(img, "n_frames", 1) or 1
    loop = int(img.info.get("loop", 0))
    duration = int(img.info.get("duration", 0))
    debugLog("animated resize:", n_frames=n_frames, loop=loop, duration=duration, get_frame=get_frame)

    if get_frame <= 0 or get_frame >= n_frames:
        # 全部保留
        pick_indices = list(range(n_frames))
    elif get_frame == 1:
        pick_indices = [0]
    else:
        # 等间隔抽帧，保留 get_frame 帧，首尾都取
        step = max(1, n_frames / get_frame)
        pick_indices = [min(int(round(i * step)), n_frames - 1) for i in range(get_frame)]

    frames = []
    for idx in pick_indices:
        img.seek(idx)
        frames.append(img.resize(target_size))

    base = frames[0].copy()
    buffer = BytesIO()
    base.save(
        buffer,
        format=img.format,
        append_images=frames[1:],
        save_all=True,
        duration=[duration] * len(frames),
        loop=loop,
    )
    return buffer

def resize_image(img: ImageFile, params: dict) -> BytesIO:
    """对单帧 / 多帧图片做缩放与（可选）抽帧。"""
    debugLog("resize_image params:", params=params)
    target_size = _calc_target_size(img.size, params.get("size"), params.get("strict_mode"))
    get_frame = params.get("get_frame", 0)

    fmt = (img.format or "").lower()
    if fmt in ANIMATED_FORMATS:
        return _resize_animated(img, target_size, get_frame)

    buffer = BytesIO()
    # 用上面 L197 已经算好的 fmt（已做 None 防护 + .lower()），
    # 不要直接 img.format.lower() — Image.new() 创建的图片 img.format 是 None
    img.resize(target_size).save(buffer, format=fmt or "PNG", mode=img.mode)
    return buffer

