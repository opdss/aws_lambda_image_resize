def lambda_handler(event, context):
    """Lambda@Edge 入口，在 Origin Response 阶段调用。"""
    debugLog(event=event)

    cf = event["Records"][0]["cf"]
    request = cf["request"]
    response = cf["response"]

    params = parse_query_string(request["querystring"])
    object_key = request["uri"].lstrip("/")
    bucket_name = extract_bucket_name(request["origin"]["s3"]["domainName"])

    # 合并所有「不需要处理」的判断
    if should_skip_processing(object_key, params):
        debugLog("skip processing, params", params=params)
        return response

    try:
        new_buffer, ext = resize_s3_image(bucket_name, object_key, params)
        if new_buffer is None:
            print("image larger than requested or invalid, skip", bucket_name, params, object_key)
            return response

        # 超出 body 上限 → 写回 S3 并重定向
        # 用 len(getvalue()) 更稳妥，tell() 依赖 cursor 位置
        if len(new_buffer.getvalue()) > MAX_RESPONSE_BODY:
            new_key = build_thumbnail_key(params, request["uri"])
            upload_to_s3(bucket_name, new_key, new_buffer, ext)
            print("resize ok, redirect", params, new_key)
            return redirect_response(response, new_key)

        print("resize ok", params, object_key)
        return build_response(response, new_buffer, ext)
    except Exception as exc:  # pragma: no cover - 线上容错
        print("resize error:", exc)
        return response